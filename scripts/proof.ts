// Summarize the proof-of-work ledgers into proof/README.md.
//
//     pnpm proof
//
// Reads proof/parasail.jsonl (every Parasail call) and proof/partners.jsonl (every You.com search and
// One action), and writes call counts by partner, model and purpose, token totals, and the first and
// last timestamps. The ledgers themselves are appended by the pipeline, the server and the scripts.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const PROOF = join(resolve(import.meta.dirname, '..'), 'proof');

interface Line {
    ts: string;
    source?: string;
    purpose?: string;
    model?: string;
    usage?: { prompt_tokens?: number; completion_tokens?: number; total_tokens?: number };
    error?: string;
    partner?: string;
    platform?: string;
    action?: string;
    dry_run?: boolean;
    backfilled?: boolean;
}

const read = (name: string): Line[] =>
    existsSync(join(PROOF, name))
        ? readFileSync(join(PROOF, name), 'utf8')
              .split('\n')
              .filter((l) => l.trim())
              .map((l) => JSON.parse(l) as Line)
        : [];

/** Rows grouped by a key, as [key, rows], biggest group first. */
function group<T>(rows: T[], key: (row: T) => string): [string, T[]][] {
    const groups = new Map<string, T[]>();
    for (const row of rows) groups.set(key(row), [...(groups.get(key(row)) ?? []), row]);
    return [...groups.entries()].sort((a, b) => b[1].length - a[1].length);
}

const tokens = (rows: Line[], field: 'prompt_tokens' | 'completion_tokens' | 'total_tokens') => rows.reduce((sum, r) => sum + (r.usage?.[field] ?? 0), 0);
const n = (x: number) => x.toLocaleString('en-US');
// "icon: garlic" and "icon: howl" count as one purpose.
const purposeOf = (r: Line) => (r.purpose ?? '').split(':')[0] || '(none)';
const span = (rows: Line[]) => {
    const times = rows.map((r) => r.ts).sort();
    return times.length ? `${times[0]} to ${times[times.length - 1]}` : 'none yet';
};

const parasail = read('parasail.jsonl');
const partners = read('partners.jsonl');

const lines = [
    '# Proof of work',
    '',
    `Every call this project made to Parasail and to the other partners, generated by \`pnpm proof\` at ${new Date().toISOString()}. The raw ledgers are [parasail.jsonl](parasail.jsonl) and [partners.jsonl](partners.jsonl), one JSON object per call. Keys, headers and One connection keys are redacted before a line is written.`,
    '',
    '## Parasail',
    '',
    `${n(parasail.length)} calls (${n(parasail.filter((r) => r.error).length)} failed), ${n(tokens(parasail, 'total_tokens'))} tokens in all: ${n(tokens(parasail, 'prompt_tokens'))} prompt and ${n(tokens(parasail, 'completion_tokens'))} completion. From ${span(parasail)}.`,
    '',
    '| Source | Purpose | Model | Calls | Tokens |',
    '|---|---|---|---|---|',
    ...group(parasail, (r) => `${r.source}|${purposeOf(r)}|${r.model}`).map(([key, rows]) => {
        const [source, purpose, model] = key.split('|');
        return `| ${source} | ${purpose} | ${model} | ${rows.length} | ${n(tokens(rows, 'total_tokens'))} |`;
    }),
    '',
    '## You.com and One',
    '',
    `${n(partners.length)} calls (${n(partners.filter((r) => r.error).length)} failed). From ${span(partners)}.`,
    '',
    '| Partner | Platform | Action | Calls | Dry runs |',
    '|---|---|---|---|---|',
    ...group(partners, (r) => `${r.partner}|${r.platform ?? ''}|${r.action}`).map(([key, rows]) => {
        const [partner, platform, action] = key.split('|');
        return `| ${partner} | ${platform || '-'} | ${action} | ${rows.length} | ${rows.filter((r) => r.dry_run).length} |`;
    }),
    '',
    partners.some((r) => r.backfilled)
        ? 'Lines marked `"backfilled": true` were added after the fact from `web/public/sfx/sounds.json`, for sounds generated before the ledger existed.\n'
        : '',
    '## Also',
    '',
    '- [exploration/](exploration/): the morning\'s model tests (tool calling, streaming, JSON schema, embeddings, SVG drawing), with their scripts and results.',
    '- [../art/prompts.jsonl](../art/prompts.jsonl): the image prompts and seeds, for re-rendering.',
    '- [../web/public/sfx/sounds.json](../web/public/sfx/sounds.json): the prompt behind each committed sound effect.',
    '',
];

writeFileSync(join(PROOF, 'README.md'), lines.join('\n'));
console.log(`Wrote proof/README.md: ${parasail.length} Parasail calls, ${partners.length} partner calls.`);
